// Concatenates includes/admin-common/*.js (in the order of files.json) and minifies them into the stable build
// input assets-src/includes/backupplus-admin-common.min.js. scripts/build-assets.php copies that to the versioned
// name the plugin enqueues. The sources are classic scripts that share the global scope, so this is a concatenation
// and not a module bundle: top-level names must survive minification, and there is nothing to tree-shake because
// the functions are called by name from PHP-printed inline scripts.
import * as esbuild from 'esbuild-wasm';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = path.join(root, 'includes/admin-common');
const outputPath = path.join(root, 'assets-src/includes/backupplus-admin-common.min.js');
const names = JSON.parse(await readFile(path.join(sourceDirectory, 'files.json'), 'utf8'));
let source = '';
for (const name of names) source += await readFile(path.join(sourceDirectory, name + '.js'), 'utf8') + '\n';
const result = await esbuild.transform(source, {
	loader: 'js',
	minify: true,
	target: 'es2019',
	legalComments: 'none',
});
// Minifying must not rename or drop anything other code reaches through the global scope.
const globals = [...source.matchAll(/^(?:async )?function ([\w$]+)|^var ([\w$]+)/gm)].map((match) => match[1] || match[2]);
const missing = globals.filter((name) => !new RegExp('(?<![\\w$.])' + name.replace(/\$/g, '\\$') + '(?![\\w$])').test(result.code));
if (missing.length) throw new Error('Minification lost global names: ' + missing.join(', '));
const content = '/* Generated by make build-assets. Source: includes/admin-common/. */\n' + result.code;
if (process.argv.includes('--check')) {
	if ((await readFile(outputPath, 'utf8').catch(() => '')) !== content)
		throw new Error('Stale admin script: run make build-assets');
	console.log('Admin script is current (' + names.length + ' files, ' + content.length + ' bytes).');
} else {
	await writeFile(outputPath, content);
	console.log('Built the admin script from ' + names.length + ' files (' + content.length + ' bytes).');
}
esbuild.stop();
