import * as esbuild from 'esbuild-wasm';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = path.join(root, 'js');
const result = await esbuild.build({
	entryPoints: {
		'backupplus-decryption-worker': path.join(root, 'assets-src/decryption/worker.mjs'),
		'backupplus-age-keygen': path.join(root, 'assets-src/decryption/keygen-ui.mjs'),
	},
	bundle: true,
	write: false,
	platform: 'browser',
	format: 'iife',
	target: ['es2022'],
	minify: true,
	legalComments: 'external',
	outdir: outputDirectory,
	plugins: [
		{
			name: 'browser-only',
			setup(build) {
				build.onResolve({ filter: /^crypto$/ }, () => ({ path: 'crypto', namespace: 'no-node' }));
				build.onLoad({ filter: /.*/, namespace: 'no-node' }, () => ({
					contents: 'module.exports = {};',
					loader: 'js',
				}));
			},
		},
	],
});
for (const file of result.outputFiles) {
	const content =
		'// Generated by npm run build:decryptor. Source: assets-src/decryption/.\n' + file.text;
	if (process.argv.includes('--check')) {
		if ((await readFile(file.path, 'utf8').catch(() => '')) !== content)
			throw new Error('Stale browser decryptor: run npm run build:decryptor');
	} else {
		await mkdir(path.dirname(file.path), { recursive: true });
		await writeFile(file.path, content);
	}
}
// Ship complete notices alongside the bundle, including dependencies whose minified source has no notice.
const packages = [
	'@noble/ciphers',
	'@noble/curves',
	'@noble/hashes',
	'@noble/post-quantum',
	'@scure/base',
	'age-encryption',
	'crypto-js',
];
let notices = 'BackupPlus browser cryptography — third-party licenses\n\n';
for (const name of packages) {
	const dir = path.join(root, 'node_modules', name);
	const pkg = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'));
	let license;
	for (const file of ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'COPYING', 'LICENCE']) {
		license = await readFile(path.join(dir, file), 'utf8').catch(() => undefined);
		if (license) break;
	}
	if (!license) throw new Error('Missing license: ' + name);
	notices += `${name} ${pkg.version}\n${license}\n\n`;
}
const licensePath = path.join(root, 'js/backupplus-decryption-LICENSE.txt');
if (process.argv.includes('--check')) {
	if ((await readFile(licensePath, 'utf8').catch(() => '')) !== notices)
		throw new Error('Stale decryptor licenses');
} else await writeFile(licensePath, notices);
esbuild.stop();
