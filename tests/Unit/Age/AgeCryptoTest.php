<?php
/** Independently generated age output must decrypt, and fresh output must round trip, for every supported identity type. These also run with the fast crypto extensions hidden. */

namespace BackupPlus\Tests\Unit\Age;

use BackupPlus\Tests\Support\AgeTestCase;
use BackupPlus_Age_Crypto;
use BackupPlus_Age_Keys;
use BackupPlus_Encryption;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;

#[RunTestsInSeparateProcesses]
#[PreserveGlobalState( false )]
final class AgeCryptoTest extends AgeTestCase {

	protected static function runs_portable(): bool {
		return true;
	}

	/** Every key type with both identity formats the restore accepts. */
	public static function reference_identities(): iterable {
		foreach ( array_keys( self::fixture_data()['keys'] ) as $type ) {
			foreach ( array( 'identity', 'encrypted_pem' ) as $format ) {
				yield $type . ' ' . $format => array( $type, $format );
			}
		}
	}

	public static function key_types(): iterable {
		foreach ( array_keys( self::fixture_data()['keys'] ) as $type ) {
			yield $type => array( $type );
		}
	}

	#[DataProvider( 'reference_identities' )]
	public function test_reference_age_output_decrypts( string $type, string $format ): void {
		$key = $this->fixture['keys'][ $type ];
		file_put_contents( $this->path, base64_decode( $key['ciphertext'] ) );
		$result = BackupPlus_Encryption::decrypt( $this->path, $key[ $format ], true, $this->password );
		$this->assertIsArray( $result, 'Reference age output must decrypt with ' . $type . ' ' . $format );
		$this->assertSame( $this->plain, file_get_contents( $result['fullpath'] ), 'Reference age output must decrypt with ' . $type . ' ' . $format );
		unlink( $result['fullpath'] );
	}

	public function test_chacha20_poly1305_matches_the_independent_aead_vector(): void {
		// RFC 8439 AEAD compatibility, independently generated by OpenSSL.
		$aead_key = str_repeat( 'k', 32 );
		$nonce    = str_repeat( 'n', 12 );
		$expected = hex2bin( 'e8964626b7a0ce3f5a069f649079729b68b701e0bca348' );
		$this->assertSame( $expected, BackupPlus_Age_Keys::aead( 'fixture', $aead_key, $nonce ), 'ChaCha20-Poly1305 must match the independent AEAD vector' );
		$this->assertSame( 'fixture', BackupPlus_Age_Keys::aead( $expected, $aead_key, $nonce, true ), 'AEAD decryption must use the same RFC 8439 construction' );
	}

	#[DataProvider( 'key_types' )]
	public function test_fresh_output_round_trips( string $type ): void {
		$key    = $this->fixture['keys'][ $type ];
		$source = $this->directory . '/database.sql';
		$bytes  = 'native' === $type ? str_repeat( "binary\0\xff", 20000 ) . 'tail' : $this->plain;
		file_put_contents( $source, $bytes );
		$encrypted = BackupPlus_Encryption::encrypt( $source, array( $key['recipient'] ), 'age' );
		$this->assertNotFalse( $encrypted, 'New age writes must use the standard format' );
		$this->assertStringStartsWith( BackupPlus_Age_Crypto::MAGIC, file_get_contents( $encrypted ), 'New age writes must use the standard format' );
		$result = BackupPlus_Encryption::decrypt( $encrypted, $key['identity'], true, $this->password );
		$this->assertIsArray( $result, 'Fresh output must roundtrip with ' . $type );
		$this->assertSame( $bytes, file_get_contents( $result['fullpath'] ), 'Fresh output must roundtrip with ' . $type );
		unlink( $result['fullpath'] );
	}
}
